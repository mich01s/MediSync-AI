"""
MediSync AI — LLM Report Generation Service
Translates clinical notes into patient-friendly, empathetic narratives.

In production mode (LLM_USE_LOCAL=false), calls the OpenAI Chat Completions API.
In local/demo mode, returns a structured mock response without network calls.
"""
from app.core.config import settings

_SYSTEM_PROMPT = """You are MediSync AI, a compassionate medical communication assistant.
Your task is to convert raw clinical notes written by a physician into a clear,
empathetic, and easy-to-understand health summary for the patient.

Guidelines:
- Use simple, non-technical language (assume the reader has no medical background).
- Structure the report with clear sections: Summary, What it Means, Your Medications,
  and Lifestyle Recommendations.
- Maintain an empathetic, reassuring, and professional tone.
- Do NOT add or invent any medical information not present in the notes.
- Format the output in clean Markdown.
"""


async def generate_patient_report(raw_clinical_notes: str) -> str:
    """
    Generate a patient-friendly report from *raw_clinical_notes*.

    Args:
        raw_clinical_notes: Clinical notes string containing complaint, vitals,
            diagnosis, and prescription.

    Returns:
        Markdown-formatted patient-friendly report string.
    """
    if settings.LLM_USE_LOCAL or not settings.LLM_API_KEY:
        return _mock_report(raw_clinical_notes)

    try:
        import httpx

        headers = {
            "Authorization": f"Bearer {settings.LLM_API_KEY}",
            "Content-Type": "application/json",
        }
        body = {
            "model": settings.LLM_MODEL,
            "messages": [
                {"role": "system", "content": _SYSTEM_PROMPT},
                {"role": "user", "content": raw_clinical_notes},
            ],
            "temperature": 0.4,
            "max_tokens": 1024,
        }

        async with httpx.AsyncClient(timeout=30.0) as client:
            response = await client.post(
                "https://api.openai.com/v1/chat/completions",
                headers=headers,
                json=body,
            )
            response.raise_for_status()
            data = response.json()
            return data["choices"][0]["message"]["content"]

    except Exception as exc:
        # Fallback to mock on any API failure — log in production
        return _mock_report(raw_clinical_notes) + f"\n\n*(LLM API error: {exc})*"


def _mock_report(notes: str) -> str:
    """
    Deterministic mock report used in development or when LLM is unavailable.
    Extracts key fields from the notes string to simulate real output.
    """
    return f"""## Health Summary Report
*Generated by MediSync AI Assistant*

---

### 📋 Summary
Based on your recent consultation, our medical team has completed a thorough
evaluation of your health status. This report summarizes the key findings in
simple terms so you can fully understand your health condition.

---

### 🔍 What It Means
Your doctor reviewed your symptoms and vital signs during this visit.
The clinical data provided has been evaluated and a treatment plan has been
prepared specifically for you.

**Clinical Notes (for reference):**
> {notes[:400]}{'...' if len(notes) > 400 else ''}

---

### 💊 Your Medications
Please take all prescribed medications as directed by your doctor.
Do not stop or modify your dosage without consulting your healthcare provider.
If you experience any side effects, contact the clinic immediately.

---

### 🌿 Lifestyle Recommendations
1. **Rest:** Ensure you get 7–8 hours of quality sleep each night.
2. **Hydration:** Drink at least 8 glasses of water daily.
3. **Diet:** Follow a balanced diet rich in vegetables, fruits, and lean proteins.
4. **Activity:** Light walking or gentle exercise is encouraged unless otherwise advised.
5. **Follow-up:** Please schedule your next appointment as recommended by your doctor.

---

*This report was generated by MediSync AI and reviewed by your attending physician.
For any questions, please contact your care team.*
"""
