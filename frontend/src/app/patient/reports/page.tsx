/**
 * MediSync AI — Patient: My Reports Page
 * Shows all doctor-approved patient-friendly clinical reports.
 */
"use client";

import { useEffect, useState } from "react";
import { FileText, CheckCircle2, ArrowLeft } from "lucide-react";
import toast from "react-hot-toast";
import { patientApi } from "@/lib/api";
import { type ClinicalReport } from "@/types";
import { Sidebar } from "@/components/ui/Sidebar";
import { LoadingSpinner, EmptyState, SectionHeader } from "@/components/ui";
import { format, parseISO } from "date-fns";

export default function PatientReportsPage() {
  const [reports, setReports] = useState<ClinicalReport[]>([]);
  const [loading, setLoading] = useState(true);
  const [selected, setSelected] = useState<ClinicalReport | null>(null);

  useEffect(() => {
    patientApi
      .getMyReports()
      .then(setReports)
      .catch(() => toast.error("Failed to load reports."))
      .finally(() => setLoading(false));
  }, []);

  /* ── Report detail view ───────────────────────────────────────────────── */
  if (selected) {
    return (
      <div className="flex min-h-screen bg-slate-50">
        <Sidebar />
        <main className="flex-1 p-8">
          <button
            className="flex items-center gap-1.5 text-sm text-primary-600 hover:underline mb-6"
            onClick={() => setSelected(null)}
          >
            <ArrowLeft size={15} />
            Back to reports
          </button>

          <div className="max-w-2xl">
            {/* Header */}
            <div className="flex items-start justify-between gap-4 mb-6">
              <div>
                <h1 className="text-xl font-bold text-slate-900">
                  Your Health Report
                </h1>
                <p className="text-sm text-slate-500 mt-1">
                  Issued:{" "}
                  {format(parseISO(selected.created_at), "PPPP")}
                </p>
              </div>
              <span className="inline-flex items-center gap-1.5 text-xs font-medium px-2.5 py-1 rounded-full bg-green-100 text-green-700">
                <CheckCircle2 size={12} />
                Doctor Approved
              </span>
            </div>

            {/* Report content */}
            <div className="card p-6">
              <div className="prose prose-sm max-w-none text-slate-700 leading-relaxed whitespace-pre-wrap">
                {selected.patient_friendly_report ?? "Report content is unavailable."}
              </div>
            </div>

            {/* Footer note */}
            <p className="mt-4 text-xs text-slate-400 text-center">
              This report was generated by MediSync AI and approved by your attending
              physician. For questions, contact your care team.
            </p>
          </div>
        </main>
      </div>
    );
  }

  /* ── Report list view ─────────────────────────────────────────────────── */
  return (
    <div className="flex min-h-screen bg-slate-50">
      <Sidebar />
      <main className="flex-1 p-8">
        <div className="mb-6">
          <h1 className="text-2xl font-bold text-slate-900">My Health Reports</h1>
          <p className="text-sm text-slate-500 mt-1">
            Personalised reports approved by your doctor
          </p>
        </div>

        <div className="card p-5">
          <SectionHeader
            title="Approved Reports"
            subtitle={`${reports.length} available`}
          />

          {loading ? (
            <div className="flex justify-center py-16">
              <LoadingSpinner />
            </div>
          ) : reports.length === 0 ? (
            <EmptyState
              icon={FileText}
              title="No reports yet"
              description="When your doctor approves a health summary, it will appear here."
            />
          ) : (
            <div className="space-y-2">
              {reports.map((r) => (
                <button
                  key={r.id}
                  className="w-full flex items-center gap-4 p-4 rounded-xl border border-slate-200
                             hover:border-primary-300 hover:bg-primary-50 text-left transition-all group"
                  onClick={() => setSelected(r)}
                >
                  {/* Icon */}
                  <div className="w-10 h-10 rounded-lg bg-green-100 flex items-center justify-center shrink-0">
                    <CheckCircle2 size={20} className="text-green-600" />
                  </div>

                  {/* Info */}
                  <div className="flex-1 min-w-0">
                    <p className="font-medium text-slate-800 group-hover:text-primary-700 transition-colors">
                      Health Summary Report
                    </p>
                    <p className="text-xs text-slate-400 mt-0.5">
                      {format(parseISO(r.created_at), "PPPP")}
                    </p>
                    {r.patient_friendly_report && (
                      <p className="text-sm text-slate-500 mt-1 line-clamp-1">
                        {r.patient_friendly_report.slice(0, 120)}…
                      </p>
                    )}
                  </div>

                  {/* Arrow */}
                  <span className="text-xs text-primary-600 font-medium shrink-0 group-hover:translate-x-0.5 transition-transform">
                    Read →
                  </span>
                </button>
              ))}
            </div>
          )}
        </div>
      </main>
    </div>
  );
}
